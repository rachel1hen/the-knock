// Read the chapter and split every line into its spoken part and its narration.
// Writes scenes/lines.gen.js, which the film and the cue exporter both read, so
// the words on the wall are the chapter's own words and cannot drift from it.
//   node tools/dump_lines.mjs
import fs from 'fs';

const src = new URL('../source/chapter_2.txt', import.meta.url);
const out = new URL('../scenes/lines.gen.js', import.meta.url);

const text = fs.readFileSync(src, 'utf8');
const raw = text.split(/\r?\n/).map(l => l.trim()).filter(Boolean);

// a spoken line is whatever sits between the first “ and its ”; the rest is narration
const quote = /“([^”]*)”/;

const LINES = raw.map((line, i) => {
  const m = line.match(quote);
  const spoken = m ? m[1].trim() : '';
  const narration = (m ? line.slice(0, m.index) + ' ' + line.slice(m.index + m[0].length) : line)
    .replace(/\s+/g, ' ').trim();
  const count = s => s ? s.split(/\s+/).filter(Boolean).length : 0;
  return { n: i + 1, line, spoken, narration, dw: count(spoken), nw: count(narration) };
});

const body = `// generated by tools/dump_lines.mjs from source/chapter_2.txt — do not edit
export const LINES = ${JSON.stringify(LINES, null, 0)};
export const LINE_COUNT = ${LINES.length};
export const SPOKEN_COUNT = ${LINES.filter(l => l.spoken).length};
`;

fs.writeFileSync(out, body);
fs.mkdirSync(new URL('../out/', import.meta.url), { recursive: true });
fs.writeFileSync(new URL('../out/lines.json', import.meta.url), JSON.stringify(LINES, null, 1));
console.log('ok', LINES.length, 'lines,', LINES.filter(l => l.spoken).length, 'spoken');

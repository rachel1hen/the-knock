// Point the whole pipeline at one chapter.
//
// Writes chapters/current.js (the static file the browser imports — the
// browser cannot read an environment variable) and chapters/current.txt (the
// chapter a plain render should use).
//
//   node tools/select_chapter.mjs [chapter]
//
// The chapter comes from the argument, then the CHAPTER variable in the
// environment (the CI workflow sets it), then the chapter already selected.
import fs from 'fs';

const root = new URL('../', import.meta.url);
const current = new URL('current.txt', new URL('chapters/', root));

const read = u => { try { return fs.readFileSync(u, 'utf8').trim(); } catch { return ''; } };

let chapter = process.argv[2] || process.env.CHAPTER || read(current) || '2';

if (!/^\d+$/.test(String(chapter))) {
  console.error('the chapter must be a number, got: ' + chapter);
  process.exit(1);
}
chapter = String(parseInt(chapter, 10));

const dir = new URL(`chapters/${chapter}/`, root);
for (const f of ['card.js', 'acts.js', 'timeline.js', 'plates.js']) {
  if (!fs.existsSync(new URL(f, dir))) {
    console.error(`chapters/${chapter} has no ${f}`);
    process.exit(1);
  }
}
if (!fs.existsSync(new URL(`source/chapter_${chapter}.txt`, root))) {
  console.error(`source/chapter_${chapter}.txt is missing`);
  process.exit(1);
}

const body = `// generated by tools/select_chapter.mjs — do not edit
//
// The film reads the chapter from here, so switching chapter is switching
// this one file. Everything else in chapters/ is a chapter's own work.
export * from './${chapter}/card.js';
export * from './${chapter}/acts.js';
export * from './${chapter}/timeline.js';
export * from './${chapter}/plates.js';
export * from './${chapter}/lines.gen.js';
`;

fs.writeFileSync(new URL('current.js', new URL('chapters/', root)), body);
fs.writeFileSync(current, chapter + '\n');
console.log('ok chapter', chapter);
